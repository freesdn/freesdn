// Generates src/lib/build-info.ts (frontend package versions) WITHOUT needing a
// full vite run. vite.config.ts generates the same file as a side effect for the
// dev server + build, but standalone `tsc --noEmit` / eslint (and CI) run before
// any vite invocation, so build-info.ts (which is gitignored, it's generated)
// would be missing and TS2307 would fail the type check on a clean checkout.
// Run this first (CI runs it right after `npm ci`; `npm run type-check` calls it).
import { execSync } from 'child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(readFileSync(path.resolve(root, 'package.json'), 'utf-8'));

const nodeVersion = process.versions.node;
let npmVersion = 'unknown';
try {
  npmVersion = execSync('npm --version', { encoding: 'utf-8' }).trim();
} catch {
  /* fallback to 'unknown' */
}

const strip = (v) => (v ?? 'unknown').replace(/^\^/, '');
const content = `// Auto-generated by scripts/gen-build-info.mjs, do not edit manually
export const FRONTEND_VERSIONS: Record<string, string> = ${JSON.stringify(
  {
    node: nodeVersion,
    npm: npmVersion,
    react: strip(pkg.dependencies?.react),
    'react-router': strip(pkg.dependencies?.['react-router-dom']),
    tailwindcss: strip(pkg.devDependencies?.tailwindcss),
    typescript: strip(pkg.devDependencies?.typescript),
    vite: strip(pkg.devDependencies?.vite),
    zustand: strip(pkg.dependencies?.zustand),
  },
  null,
  2,
)};
`;

mkdirSync(path.resolve(root, 'src/lib'), { recursive: true });
writeFileSync(path.resolve(root, 'src/lib/build-info.ts'), content);
console.log('generated src/lib/build-info.ts');
